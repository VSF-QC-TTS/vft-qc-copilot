package vn.vinfast.vfqc.api.runner.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import java.util.UUID;
import vn.vinfast.vfqc.api.runner.enums.RunnerInstanceStatus;

public record RunnerHeartbeatRequest(
    @Schema(description = "Stable runner key generated by the runner deployment.", example = "runner-prod-a")
        @NotBlank(message = "Runner key is required")
        String runnerKey,
    @Schema(description = "Current runner status.", example = "BUSY") RunnerInstanceStatus status,
    @Schema(description = "Command currently being processed.", example = "6c0f4306-883b-43b6-94fd-826d14c33074")
        UUID currentCommandId,
    @Schema(description = "Test run currently being processed.", example = "27a47393-169d-4f01-92a0-59cf2dc10f8a")
        UUID currentTestRunId) {}
